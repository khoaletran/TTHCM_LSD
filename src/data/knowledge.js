// Helper truy xuất kiến thức theo môn học và chương
export function getKnowledgeBySubject(subjectId) {
  return subjectId === 'lsd' ? KNOWLEDGE_LSD : KNOWLEDGE_TTHCM;
}

export function getKnowledgeByChapter(subjectId, chapterId) {
  const bank = getKnowledgeBySubject(subjectId);
  return bank[chapterId] || null;
}
